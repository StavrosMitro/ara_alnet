        net->conv1.in_h = CONV1_PADDED_H;
        net->conv1.in_units = CONV1_PADDED_IN_UNITS;
        
        // --- VECTORIZED MEMCPY FOR INPUT ---
        memcpy_vectorized_f16(train_input_buf,
            test_inputs,
            (size_t)net->batchsize * CONV1_IN_UNITS);
            
