def benchmark_training(use_amp=False, num_epochs=5, batch_size=256):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model = VGGMini(num_classes=100).to(device)
    optimizer = optim.SGD(model.parameters(), lr=0.01)
    criterion = nn.CrossEntropyLoss()
    scaler = GradScaler('cuda') if use_amp else None

    # Generate dummy data to focus on compute speed rather than disk I/O
    dummy_input = torch.randn(batch_size, 3, 32, 32).to(device)
    dummy_target = torch.randint(0, 100, (batch_size,)).to(device)

    print(f"Starting benchmark: {'FP16 (Mixed Precision)' if use_amp else 'FP32 (Standard)'}...")

    # Warm-up
    for _ in range(2):
        with autocast('cuda', enabled=use_amp):
            output = model(dummy_input)
            loss = criterion(output, dummy_target)
        if use_amp:
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
        else:
            loss.backward()
            optimizer.step()
        optimizer.zero_grad()

    torch.cuda.synchronize()
    start_time = time.time()

    for epoch in range(num_epochs):
        # Simulate 100 steps per epoch
        for _ in range(100):
            optimizer.zero_grad()
            with autocast('cuda', enabled=use_amp):
                output = model(dummy_input)
                loss = criterion(output, dummy_target)

            if use_amp:
                scaler.scale(loss).backward()
                scaler.step(optimizer)
                scaler.update()
            else:
                loss.backward()
                optimizer.step()

    torch.cuda.synchronize()
    end_time = time.time()

    avg_time = (end_time - start_time) / num_epochs
    print(f"Average time per epoch: {avg_time:.4f} seconds")
    return avg_time

